using UnityEngine;
using UnityEngine.SceneManagement;

public class GameManager : MonoBehaviour
{
    public static GameManager instance;

    [Header("UI References")]
    [SerializeField] private GameObject gameOverPanel;

    private bool isGameOver = false;

    [Header("Audio Settings")]
    public AudioSource gameManagerAudio;
    public AudioClip gameOverSound;

    void Awake()
    {
        if (instance == null)
            instance = this;
        else
            Destroy(gameObject);
    }

    void Start()
    {
        Time.timeScale = 1f;

        // 1. AUTO-FIX: Ensure EventSystem exists (without it, UI buttons CANNOT be clicked!)
        if (FindAnyObjectByType<UnityEngine.EventSystems.EventSystem>() == null)
        {
            GameObject es = new GameObject("EventSystem_AutoGenerated");
            es.AddComponent<UnityEngine.EventSystems.EventSystem>();
            es.AddComponent<UnityEngine.EventSystems.StandaloneInputModule>();
            Debug.Log("GameManager: Created missing EventSystem for UI!");
        }

        if (gameOverPanel != null)
        {
            // 2. AUTO-FIX: Programmatically link the Restart button (so you don't have to do it in Inspector!)
            UnityEngine.UI.Button restartBtn = gameOverPanel.GetComponentInChildren<UnityEngine.UI.Button>(true);
            if (restartBtn != null)
            {
                restartBtn.onClick.RemoveAllListeners();
                restartBtn.onClick.AddListener(RestartGame);
                Debug.Log("GameManager: Automatically linked the Restart Button!");
            }

            gameOverPanel.SetActive(false);
        }
    }

    public void TriggerGameOver()
    {
        if (isGameOver) return;

        isGameOver = true;
        Debug.Log("Game Over triggered!");

        // Play the game over sound
        if (gameManagerAudio != null && gameOverSound != null)
        {
            gameManagerAudio.PlayOneShot(gameOverSound);
        }

        // Time.timeScale = 0f; // Ab time nahi rukega, background real-time chalega!
        Cursor.lockState = CursorLockMode.None;
        Cursor.visible = true;

        StartCoroutine(GameOverSequence());
    }

    private System.Collections.IEnumerator GameOverSequence()
    {
        // Wait for player to fall down and enemy to vanish
        yield return new WaitForSeconds(2.5f); 
        
        if (gameOverPanel != null)
        {
            gameOverPanel.SetActive(true);
            CanvasGroup cg = gameOverPanel.GetComponent<CanvasGroup>();
            if (cg != null)
            {
                cg.blocksRaycasts = true;
                cg.interactable = true;
                cg.alpha = 0f;
                while (cg.alpha < 1f)
                {
                    cg.alpha += Time.deltaTime * 0.5f; // Slow cinematic fade in
                    // Force cursor unlock repeatedly just in case another script locks it
                    Cursor.lockState = CursorLockMode.None;
                    Cursor.visible = true;
                    yield return null;
                }
            }
            
            // Final guarantee for cursor
            Cursor.lockState = CursorLockMode.None;
            Cursor.visible = true;
        }
    }

    public void RestartGame()
    {
        isGameOver = false;
        Time.timeScale = 1f;
        SceneManager.LoadScene(SceneManager.GetActiveScene().buildIndex);
    }

    public bool IsGameOver() => isGameOver;
}
