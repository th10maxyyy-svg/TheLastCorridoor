using UnityEngine;
using UnityEngine.SceneManagement;

public class GameManager : MonoBehaviour
{
    public static GameManager instance;

    [Header("UI References")]
    [SerializeField] private GameObject gameOverPanel;

    private bool isGameOver = false;
    private GameProgress.RunSummary failureSummary; // ENDING "Consumed" (FR_54, FR_56)

    [Header("Audio Settings")]
    public AudioSource gameManagerAudio;
    public AudioClip gameOverSound;

    [Header("Background Music")]
    [SerializeField] private AudioSource bgmAudioSource;
    [SerializeField] private AudioClip backgroundAmbience; // Madham horror sound (Drone)

    void Awake()
    {
        if (instance == null)
            instance = this;
        else
            Destroy(gameObject);
    }

    void Start()
    {
        Time.timeScale = 1f;

        // AUTO-FIX: Create background music audio source if missing
        if (bgmAudioSource == null)
        {
            bgmAudioSource = gameObject.AddComponent<AudioSource>();
            bgmAudioSource.spatialBlend = 0f; // 2D sound so it plays everywhere equally
            bgmAudioSource.loop = true; // Loop forever
            bgmAudioSource.volume = 0.4f; // Keep it low/madham
        }

        // Start playing background horror ambience if assigned
        if (backgroundAmbience != null && !bgmAudioSource.isPlaying)
        {
            bgmAudioSource.clip = backgroundAmbience;
            bgmAudioSource.Play();
        }

        // 1. AUTO-FIX: Ensure EventSystem exists (without it, UI buttons CANNOT be clicked!)
        if (FindAnyObjectByType<UnityEngine.EventSystems.EventSystem>() == null)
        {
            GameObject es = new GameObject("EventSystem_AutoGenerated");
            es.AddComponent<UnityEngine.EventSystems.EventSystem>();
            es.AddComponent<UnityEngine.EventSystems.StandaloneInputModule>();
            Debug.Log("GameManager: Created missing EventSystem for UI!");
        }

        if (gameOverPanel != null)
        {
            // 2. AUTO-FIX: Programmatically link the Restart button (so you don't have to do it in Inspector!)
            UnityEngine.UI.Button restartBtn = gameOverPanel.GetComponentInChildren<UnityEngine.UI.Button>(true);
            if (restartBtn != null)
            {
                restartBtn.onClick.RemoveAllListeners();
                restartBtn.onClick.AddListener(RestartGame);
                Debug.Log("GameManager: Automatically linked the Restart Button!");
            }

            gameOverPanel.SetActive(false);
        }
    }

    public void TriggerGameOver()
    {
        if (isGameOver) return;
        isGameOver = true;
        Debug.Log("Game Over triggered!");

        // Play the game over sound
        if (gameManagerAudio != null && gameOverSound != null)
        {
            gameManagerAudio.PlayOneShot(gameOverSound);
        }

        if (SaveManager.instance != null)
        {
            // HARDCORE MECHANIC: Drop item on death (Inventory saves where it lands)
            GameObject player = GameObject.FindGameObjectWithTag("Player");
            if (player != null)
            {
                Inventory inv = player.GetComponent<Inventory>();
                if (inv != null && inv.HasItem())
                {
                    inv.DropCurrentItem();
                }
            }

            SaveManager.instance.DecreaseLife();
            int remainingLives = SaveManager.instance.currentSaveData.lives;

            if (remainingLives > 0)
            {
                // Cinematic Death (Life 1 & 2)
                if (RespawnManager.instance != null)
                {
                    RespawnManager.instance.TriggerCinematicDeath(remainingLives, player);
                }
                else
                {
                    // Failsafe: no RespawnManager in the scene - still respawn instead of leaving the player stuck
                    StartCoroutine(FallbackRespawn());
                }
                return; // Stop here, the respawn will reload the scene
            }
            else
            {
                // Final Death (Permadeath)
                // ENDINGS: record the failure ending + run statistics BEFORE the save is wiped
                failureSummary = GameProgress.FinishRun(false);
                SaveManager.instance.DeleteSave();
            }
        }

        // Fallback or Permadeath
        Cursor.lockState = CursorLockMode.None;
        Cursor.visible = true;
        StartCoroutine(GameOverSequence());
    }

    private System.Collections.IEnumerator GameOverSequence()
    {
        // Wait for player to fall down and enemy to vanish
        yield return new WaitForSeconds(2.5f); 

        // ENDING SUMMARY (FR_56): show which ending this was and the run statistics, then the normal game over panel
        if (failureSummary != null)
        {
            GameUI.ShowEndingSummary(failureSummary);
            failureSummary = null;
            while (GameUI.IsSummaryOpen) yield return null;
        }
        
        if (gameOverPanel != null)
        {
            gameOverPanel.SetActive(true);
            CanvasGroup cg = gameOverPanel.GetComponent<CanvasGroup>();
            if (cg != null)
            {
                cg.blocksRaycasts = true;
                cg.interactable = true;
                cg.alpha = 0f;
                while (cg.alpha < 1f)
                {
                    cg.alpha += Time.deltaTime * 0.5f; // Slow cinematic fade in
                    // Force cursor unlock repeatedly just in case another script locks it
                    Cursor.lockState = CursorLockMode.None;
                    Cursor.visible = true;
                    yield return null;
                }
            }
            
            // Final guarantee for cursor
            Cursor.lockState = CursorLockMode.None;
            Cursor.visible = true;
        }
    }

    private System.Collections.IEnumerator FallbackRespawn()
    {
        yield return new WaitForSeconds(3f);
        IntroState.skipIntro = true;
        Time.timeScale = 1f;
        SceneManager.LoadScene(SceneManager.GetActiveScene().buildIndex);
    }

    public void RestartGame()
    {
        isGameOver = false;
        Time.timeScale = 1f;
        IntroState.ResetForNewGame(); // Permadeath = brand new game, so the intro plays again
        SceneManager.LoadScene(SceneManager.GetActiveScene().buildIndex);
    }

    public bool IsGameOver() => isGameOver;
}
